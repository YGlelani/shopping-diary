CREATE TABLE shopping_plan_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    list_id bigint,
    list_name varchar(200) NOT NULL,
    name varchar(200) NOT NULL,
    strategy varchar(20) NOT NULL CHECK (strategy IN ('ONE_STORE','SPLIT','ALTERNATIVES')),
    assumptions jsonb NOT NULL,
    estimate jsonb NOT NULL,
    calculated_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    request_id uuid NOT NULL,
    FOREIGN KEY (list_id,user_id) REFERENCES shopping_lists(id,user_id) ON DELETE SET NULL (list_id),
    UNIQUE (user_id,request_id)
);
CREATE INDEX idx_shopping_plan_owner_history ON shopping_plan_snapshots(user_id,id DESC);
