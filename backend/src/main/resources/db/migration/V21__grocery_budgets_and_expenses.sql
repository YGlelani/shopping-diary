CREATE TABLE grocery_budgets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name varchar(200) NOT NULL,
    description varchar(1000),
    amount numeric(10,2) NOT NULL CHECK (amount >= 0),
    period varchar(12) NOT NULL CHECK (period IN ('TRIP','WEEKLY','FORTNIGHTLY','MONTHLY','CUSTOM')),
    starts_on date NOT NULL,
    ends_on date NOT NULL CHECK (ends_on >= starts_on),
    status varchar(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ARCHIVED')),
    revision bigint NOT NULL DEFAULT 0,
    request_id uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    snapshot_subtotal numeric(20,2),
    snapshot_entries integer,
    snapshot_priced integer,
    snapshot_at timestamptz,
    snapshot_single_branch boolean,
    UNIQUE (id, user_id),
    UNIQUE (user_id, request_id)
);
CREATE INDEX idx_grocery_budgets_owner ON grocery_budgets (user_id, id DESC);

ALTER TABLE shopping_lists ADD CONSTRAINT uq_shopping_list_owner UNIQUE (id, user_id);
CREATE TABLE grocery_budget_lists (
    budget_id bigint NOT NULL,
    list_id bigint NOT NULL,
    user_id bigint NOT NULL,
    PRIMARY KEY (budget_id, list_id),
    FOREIGN KEY (budget_id, user_id) REFERENCES grocery_budgets(id, user_id) ON DELETE CASCADE,
    FOREIGN KEY (list_id, user_id) REFERENCES shopping_lists(id, user_id) ON DELETE CASCADE
);
CREATE INDEX idx_grocery_budget_lists_list ON grocery_budget_lists (list_id);

CREATE TABLE grocery_expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_id bigint NOT NULL,
    user_id bigint NOT NULL,
    list_id bigint,
    branch_id bigint REFERENCES stores(id) ON DELETE SET NULL,
    amount numeric(10,2) NOT NULL CHECK (amount > 0),
    purchased_on date NOT NULL,
    description varchar(300) NOT NULL,
    category varchar(100),
    request_id uuid NOT NULL,
    revision bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (budget_id, user_id) REFERENCES grocery_budgets(id, user_id) ON DELETE CASCADE,
    FOREIGN KEY (list_id, user_id) REFERENCES shopping_lists(id, user_id) ON DELETE SET NULL (list_id),
    UNIQUE (user_id, request_id)
);
CREATE INDEX idx_grocery_expenses_history ON grocery_expenses (budget_id, purchased_on DESC, id DESC);
