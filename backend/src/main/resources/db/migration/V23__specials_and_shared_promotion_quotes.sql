CREATE VIEW promotion_branch_scope AS
SELECT p.id AS promotion_id, s.id AS store_id
FROM promotions p
JOIN stores anchor ON anchor.id=p.store_id
JOIN retailers r ON r.id=anchor.retailer_id AND r.active
JOIN stores s ON s.retailer_id=r.id AND s.active AND upper(s.store_code) IS DISTINCT FROM 'ONLINE'
WHERE (p.scope='BRANCH' AND s.id=anchor.id)
   OR p.scope='NATIONAL'
   OR (p.scope='REGION' AND lower(s.province)=lower(p.region));

CREATE OR REPLACE VIEW current_branch_promotions AS
SELECT p.id,p.product_id,a.store_id,p.promo_type,p.description,p.promo_price,p.min_quantity,
       p.start_date,p.end_date,p.status,p.created_at,p.title,p.scope,p.region,p.loyalty_program,p.percent_off,
       p.free_quantity,p.source_type,p.source_reference,p.source_key,p.collected_at,p.updated_at,p.verification,p.revision
FROM promotions p JOIN promotion_branch_scope a ON a.promotion_id=p.id
WHERE p.status IN ('ACTIVE','SCHEDULED')
  AND (CURRENT_TIMESTAMP AT TIME ZONE 'Africa/Johannesburg')::date BETWEEN p.start_date AND p.end_date
  AND p.verification <> 'UNVERIFIED'
  AND ((p.promo_type='DISCOUNT' AND p.promo_price>0 AND coalesce(p.min_quantity,1)>=1)
    OR (p.promo_type='MULTIBUY' AND p.promo_price>0 AND p.min_quantity>1)
    OR (p.promo_type='PERCENT' AND p.percent_off>0 AND coalesce(p.min_quantity,1)>=1)
    OR (p.promo_type='BOGOF' AND p.free_quantity>0 AND p.min_quantity>0)
    OR (p.promo_type='MEMBER' AND p.promo_price>0 AND p.loyalty_program IS NOT NULL));

-- Each candidate is calculated independently against the shelf price, so competing discounts never stack.
CREATE FUNCTION promotion_quantity_total(kind text, shelf numeric, quantity numeric, amount numeric,
    minimum integer, percent_off numeric, free_quantity integer, program text, member_confirmed boolean)
RETURNS numeric LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN quantity < coalesce(minimum,1) OR quantity<=0 THEN NULL
        WHEN (kind='MEMBER' OR program IS NOT NULL) AND NOT member_confirmed THEN NULL
        WHEN kind IN ('DISCOUNT','MEMBER') AND amount>0 THEN round(quantity*amount,2)
        WHEN kind='PERCENT' AND shelf>0 AND percent_off>0 AND percent_off<=100
            THEN round(quantity*round(shelf*(100-percent_off)/100,2),2)
        WHEN kind='MULTIBUY' AND minimum>1 AND amount>0 AND (shelf>0 OR mod(quantity,minimum)=0)
            THEN round(trunc(quantity/minimum)*amount+coalesce(shelf,0)*mod(quantity,minimum),2)
        WHEN kind='BOGOF' AND shelf>0 AND minimum>0 AND free_quantity>0 AND quantity>=minimum+free_quantity
            THEN round((quantity-trunc(quantity/(minimum+free_quantity))*free_quantity)*shelf,2)
        END
$$;

CREATE FUNCTION eligible_branch_observation(product bigint, branch bigint, max_age_days integer)
RETURNS SETOF price_observations LANGUAGE sql STABLE AS $$
    SELECT latest.* FROM (
        SELECT po.* FROM price_observations po WHERE po.product_id=product AND po.store_id=branch
          AND po.observed_at<=CURRENT_TIMESTAMP ORDER BY po.observed_at DESC,po.id DESC LIMIT 1
    ) latest
    WHERE latest.stock_status='IN_STOCK'
      AND latest.verification_status IN ('VERIFIED','UNVERIFIED')
      AND latest.observed_at>=CURRENT_TIMESTAMP-make_interval(days=>least(max_age_days,
          CASE WHEN latest.source_type IN ('COMMUNITY','RECEIPT','BROCHURE') THEN 3 ELSE max_age_days END))
      AND (latest.shelf_price>0 OR latest.promo_price>0)
$$;

CREATE FUNCTION unstructured_public_price(observation price_observations)
RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN observation.promo_price>0 AND NOT EXISTS (
        SELECT 1 FROM promotions p JOIN promotion_branch_scope a ON a.promotion_id=p.id
        WHERE p.product_id=observation.product_id AND a.store_id=observation.store_id
          AND p.promo_price=observation.promo_price
    ) THEN observation.promo_price END
$$;

CREATE FUNCTION branch_quantity_quote(product bigint, branch bigint, max_age_days integer,
    quantity numeric, member_confirmed boolean DEFAULT false, ignore_promotions boolean DEFAULT false)
RETURNS TABLE(total numeric, promotion_id bigint, promotion_ends_on date, price_type text, shelf_total numeric)
LANGUAGE sql STABLE AS $$
    SELECT choice.total,choice.promotion_id,choice.promotion_ends_on,choice.price_type,
           CASE WHEN obs.shelf_price>0 THEN round(obs.shelf_price*quantity,2) END
    FROM eligible_branch_observation(product,branch,max_age_days) obs
    CROSS JOIN LATERAL (
        SELECT candidate.* FROM (
            SELECT round(obs.shelf_price*quantity,2) AS total, NULL::bigint AS promotion_id,
                   NULL::date AS promotion_ends_on,'SHELF'::text AS price_type WHERE obs.shelf_price>0
            UNION ALL
            SELECT round(unstructured_public_price(obs)*quantity,2),NULL,NULL,'PROMOTION' WHERE NOT ignore_promotions
            UNION ALL
            SELECT promotion_quantity_total(p.promo_type,obs.shelf_price,quantity,p.promo_price,p.min_quantity,
                       p.percent_off,p.free_quantity,p.loyalty_program,member_confirmed),p.id,p.end_date,p.promo_type
            FROM current_branch_promotions p
            WHERE p.product_id=product AND p.store_id=branch AND NOT ignore_promotions
        ) candidate WHERE candidate.total IS NOT NULL AND quantity>0
        ORDER BY candidate.total,(candidate.price_type='SHELF') DESC,candidate.promotion_id NULLS LAST LIMIT 1
    ) choice
$$;

CREATE OR REPLACE FUNCTION current_branch_price(product bigint, branch bigint, max_age_days integer)
RETURNS TABLE(shelf_price numeric,promo_price numeric,member_price numeric,unit_price numeric,
    observed_at timestamptz,verification_status varchar,stock_status varchar,source_type varchar,effective_price numeric)
LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN obs.shelf_price>0 THEN obs.shelf_price END,
           CASE WHEN q.price_type<>'SHELF' THEN q.total END,
           CASE WHEN obs.member_price>0 THEN obs.member_price END,obs.unit_price,
           obs.observed_at,obs.verification_status,obs.stock_status,obs.source_type,q.total
    FROM eligible_branch_observation(product,branch,max_age_days) obs
    CROSS JOIN LATERAL branch_quantity_quote(product,branch,max_age_days,1) q
$$;

CREATE FUNCTION shopping_list_item_quote(item shopping_list_items, branch bigint, max_age_days integer,
    member_confirmed boolean DEFAULT false, ignore_promotions boolean DEFAULT false)
RETURNS TABLE(product_id bigint,product_name varchar,total numeric,promotion_id bigint,promotion_ends_on date,
    price_type text,shelf_total numeric)
LANGUAGE sql STABLE AS $$
    SELECT p.id,p.canonical_name,q.total,q.promotion_id,q.promotion_ends_on,q.price_type,q.shelf_total
    FROM products p CROSS JOIN LATERAL branch_quantity_quote(p.id,branch,max_age_days,item.quantity,
        member_confirmed,ignore_promotions) q
    WHERE (p.id=item.product_id OR (item.flexible_brand AND p.id=item.substitute_product_id))
      AND (item.unit IS NULL OR item.unit IN ('item','pack','bottle','carton','bag'))
      AND (item.flexible_brand OR item.preferred_brand IS NULL OR lower(p.brand)=lower(item.preferred_brand))
    ORDER BY q.total,(lower(p.brand)=lower(item.preferred_brand)) DESC NULLS LAST,(p.id=item.product_id) DESC,p.id
    LIMIT 1
$$;

CREATE OR REPLACE FUNCTION shopping_list_item_offer(item shopping_list_items, branch bigint, max_age_days integer)
RETURNS TABLE(product_id bigint,product_name varchar,total numeric) LANGUAGE sql STABLE AS $$
    SELECT q.product_id,q.product_name,q.total FROM shopping_list_item_quote(item,branch,max_age_days) q
$$;
CREATE FUNCTION record_promotion_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN RETURN NEW; END IF;
    INSERT INTO promotion_audit(promotion_id,actor_id,action,before_record,after_record)
    VALUES(NEW.id,nullif(current_setting('shopping_diary.promotion_actor',true),'')::bigint,
           CASE WHEN TG_OP='INSERT' THEN 'CREATED'
                WHEN OLD.status IS DISTINCT FROM NEW.status THEN NEW.status ELSE 'UPDATED' END,
           CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) END,to_jsonb(NEW));
    RETURN NEW;
END
$$;
CREATE TRIGGER promotion_audit_changes AFTER INSERT OR UPDATE ON promotions
FOR EACH ROW EXECUTE FUNCTION record_promotion_audit();
