CREATE TABLE branch_directory_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitted_by bigint REFERENCES users(id) ON DELETE SET NULL,
    retailer_id bigint NOT NULL REFERENCES retailers(id),
    name varchar(255) NOT NULL,
    address varchar(500) NOT NULL,
    city varchar(100) NOT NULL,
    province varchar(100) NOT NULL,
    lat numeric NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lon numeric NOT NULL CHECK (lon BETWEEN -180 AND 180),
    source_url varchar(500) NOT NULL,
    status varchar(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    branch_id bigint REFERENCES stores(id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX idx_directory_pending_site
    ON branch_directory_submissions (retailer_id, lower(btrim(name)), lower(btrim(city)))
    WHERE status = 'PENDING';
