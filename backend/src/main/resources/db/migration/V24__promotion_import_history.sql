CREATE TABLE promotion_import_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(24) NOT NULL,
    retailer_slug varchar(80),
    store_code varchar(80),
    status varchar(12) NOT NULL CHECK (status IN ('RUNNING','SUCCEEDED','FAILED')),
    summary jsonb,
    error_message varchar(500),
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz
);
CREATE INDEX idx_promotion_import_history ON promotion_import_runs(id DESC);
